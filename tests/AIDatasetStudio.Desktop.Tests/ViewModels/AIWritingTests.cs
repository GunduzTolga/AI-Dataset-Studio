    [Fact]
    public Task The_model_writes_the_output_which_is_saved_with_the_model_in_the_lineage() => UiTest.RunAsync(async () =>
    {
        await using var host = new DesktopTestHost();
        var dataset = await host.CreateDatasetAsync(DatasetType.Instruction, [new InstructionPayload("Kargo ücreti ne kadar?", "Sipariş 600 TL.", "eski")]);
        await host.Get<Application.Catalog.ICatalogService>().SetAIGuidanceAsync(dataset.Id, "Tek cümle yaz.");
        dataset.AIGuidance = "Tek cümle yaz.";
        host.AddAIConnection();
        var details = host.Main.Details;
        var row = host.Main.Records.Items[0];
        host.Main.Records.SelectedItem = row;
        await host.WaitForDetailsAsync(row.Id);
        host.AI.Hold = new TaskCompletionSource();
        host.AI.Answers.Enqueue(["500 TL üzeri ", "siparişlerde ", "kargo ücretsizdir."]);
        // What a Save button shows: the state as of the command's last change notification.
        bool? saveEnabled = null;
        details.SaveCommand.CanExecuteChanged += (_, _) => saveEnabled = details.SaveCommand.CanExecute(null);

        var writing = details.WriteCommand.ExecuteAsync(AIWriteTarget.Answer);
        await DesktopTestHost.WaitUntilAsync(() => details.Fields[3].IsWriting && host.AI.Requests.Count == 1);

        Assert.True(details.IsWriting);
        Assert.Equal("Writing with qwen2.5:7b…", details.WritingText);
        Assert.False(details.WriteCommand.CanExecute(AIWriteTarget.Answer));
        Assert.False(details.SaveCommand.CanExecute(null));
        var (_, request) = Assert.Single(host.AI.Requests);
        Assert.EndsWith("Instructions for this dataset:\nTek cümle yaz.", request.Messages[0].Content, StringComparison.Ordinal);
        Assert.Equal("Kargo ücreti ne kadar?\n\nSipariş 600 TL.", request.Messages[1].Content);
        Assert.Equal((0.7, 2048), (request.Temperature, request.MaxTokens));

        host.AI.Hold.SetResult();
        await writing;

        Assert.False(details.IsWriting);
        Assert.False(details.Fields[3].IsWriting);
        Assert.Equal("500 TL üzeri siparişlerde kargo ücretsizdir.", details.Fields[3].Text);
        Assert.True(details.IsDirty);
        Assert.True(saveEnabled);
        Assert.Equal("qwen2.5:7b wrote the answer; review it before approving", host.Main.Status.Message);

        await details.SaveCommand.ExecuteAsync(null);
        var saved = await host.Get<IRecordQueryService>().GetAsync(row.Id);
        Assert.Equal("qwen2.5:7b", saved!.Lineage.GeneratedByModel);
        Assert.Equal(RecordStatus.InReview, saved.Status);
        Assert.Contains(details.Info, item => item.Label == "Generated by" && item.Value == "qwen2.5:7b");

        // Undo takes back the content and the note in the lineage.
        await host.Main.UndoCommand.ExecuteAsync(null);
        var undone = await host.Get<IRecordQueryService>().GetAsync(row.Id);
        Assert.Equal(("eski", null), (((InstructionPayload)undone!.Payload).Output, undone.Lineage.GeneratedByModel));
    });

    [Fact]
    public Task Stopping_keeps_what_was_written_and_an_error_brings_back_the_old_text() => UiTest.RunAsync(async () =>
    {
        await using var host = new DesktopTestHost();
        await host.CreateDatasetAsync(DatasetType.Instruction, [new InstructionPayload("Soru?", "", "eski yanıt")]);
        host.AddAIConnection();
        var details = host.Main.Details;
        var row = host.Main.Records.Items[0];
        host.Main.Records.SelectedItem = row;
        await host.WaitForDetailsAsync(row.Id);

        host.AI.Hold = new TaskCompletionSource();
        host.AI.Answers.Enqueue(["Yarım ", "kalan yanıt"]);
        var writing = details.WriteMainCommand.ExecuteAsync(null);
        await DesktopTestHost.WaitUntilAsync(() => details.IsWriting && host.AI.Requests.Count == 1);
        await details.WriteMainCommand.ExecuteAsync(null); // Mod+G again stops
        await writing;

        Assert.Equal("Yarım ", details.Fields[3].Text);
        Assert.Equal("Writing stopped; the text so far is kept", host.Main.Status.Message);

        host.AI.Hold = null;
        host.AI.Failure = new AIException(AIErrorKind.Unreachable, "down");
        await details.WriteCommand.ExecuteAsync(AIWriteTarget.Answer);

        Assert.Equal("Yarım ", details.Fields[3].Text);
        Assert.Equal("Nothing answers at http://localhost:11434/v1. Is Ollama running?", details.AIError);
        details.DismissAIErrorCommand.Execute(null);
        Assert.False(details.HasAIError);
    });

    [Fact]
    public Task Without_a_connection_or_a_question_the_editor_says_what_is_missing() => UiTest.RunAsync(async () =>
    {
        await using var host = new DesktopTestHost();
        await host.CreateDatasetAsync(DatasetType.Instruction, [new InstructionPayload(" ", "", "")]);
        var details = host.Main.Details;
        var row = host.Main.Records.Items[0];

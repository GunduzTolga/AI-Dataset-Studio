        Assert.Equal("Write the question first; the model answers it.", details.AIError);
        Assert.Empty(host.AI.Requests);
        Assert.False(details.IsDirty);
    });

    [Fact]
    public Task A_reply_continues_the_conversation_and_a_last_answer_is_written_again() => UiTest.RunAsync(async () =>
    {
        await using var host = new DesktopTestHost();
        await host.CreateDatasetAsync(DatasetType.Chat, [new ChatPayload("Sen bir kargo asistanısın.", [new ChatMessage(ChatRole.User, "Kargom nerede?")])]);
        host.AddAIConnection();
        var details = host.Main.Details;
        var row = host.Main.Records.Items[0];
        host.Main.Records.SelectedItem = row;
        await host.WaitForDetailsAsync(row.Id);
        Assert.False(details.WriteCommand.CanExecute(AIWriteTarget.Answer));
        host.AI.Answers.Enqueue(["Takip numaranızı ", "paylaşır mısınız?"]);
        host.AI.Answers.Enqueue(["Sipariş numaranız nedir?"]);

        await details.WriteCommand.ExecuteAsync(AIWriteTarget.Reply);

        Assert.Equal([(ChatRole.User, "Kargom nerede?"), (ChatRole.Assistant, "Takip numaranızı paylaşır mısınız?")], details.Messages.Select(m => (m.Role, m.Text)));
        var (_, first) = host.AI.Requests.First();
        Assert.StartsWith("Sen bir kargo asistanısın.", first.Messages[0].Content, StringComparison.Ordinal);
        Assert.Equal([ChatRole.System, ChatRole.User], first.Messages.Select(m => m.Role));

        await details.WriteMainCommand.ExecuteAsync(null);
        Assert.Equal(2, details.Messages.Count);
        Assert.Equal("Sipariş numaranız nedir?", details.Messages[1].Text);
        Assert.Equal(2, host.AI.Requests.Last().Request.Messages.Count);
    });

    [Fact]
    public Task Preference_pairs_get_a_chosen_and_a_worse_rejected_answer() => UiTest.RunAsync(async () =>
    {
        await using var host = new DesktopTestHost();
        await host.CreateDatasetAsync(DatasetType.Preference, [new PreferencePayload("İade süresi nedir?", "14 gün içinde iade edebilirsiniz.", "")]);
        host.AddAIConnection();
        var details = host.Main.Details;
        var row = host.Main.Records.Items[0];
        host.Main.Records.SelectedItem = row;
        await host.WaitForDetailsAsync(row.Id);
        host.AI.Answers.Enqueue(["Bilmiyorum, sanırım bir hafta."]);

        await details.WriteCommand.ExecuteAsync(AIWriteTarget.Rejected);

        Assert.Equal(("14 gün içinde iade edebilirsiniz.", "Bilmiyorum, sanırım bir hafta."), (details.Fields[1].Text, details.Fields[2].Text));
        var (_, request) = Assert.Single(host.AI.Requests);
        Assert.Contains("rejected answer of a preference (DPO) training pair", request.Messages[0].Content, StringComparison.Ordinal);
        Assert.Contains("14 gün içinde iade edebilirsiniz.", request.Messages[1].Content, StringComparison.Ordinal);
        Assert.Equal(new[] { true, true }, new[] { details.Fields[1].CanBeWritten, details.Fields[2].CanBeWritten });
        Assert.False(details.Fields[0].CanBeWritten);
    });

    [Fact]
    public Task Moving_to_another_record_stops_writing_and_saves_what_was_written() => UiTest.RunAsync(async () =>
    {
        await using var host = new DesktopTestHost();
        await host.CreateDatasetAsync(DatasetType.Instruction, [new InstructionPayload("Bir?", "", ""), new InstructionPayload("İki?", "", "")]);
        host.AddAIConnection();
        var details = host.Main.Details;
        var records = host.Main.Records;
        records.SelectedItem = records.Items[0];
        await host.WaitForDetailsAsync(records.Items[0].Id);
        host.AI.Hold = new TaskCompletionSource();
        host.AI.Answers.Enqueue(["Bir ", "yanıt"]);
        _ = details.WriteCommand.ExecuteAsync(AIWriteTarget.Answer);
        await DesktopTestHost.WaitUntilAsync(() => details.IsWriting && host.AI.Requests.Count == 1);

        records.SelectedItem = records.Items[1];
        await host.WaitForDetailsAsync(records.Items[1].Id);

        Assert.False(details.IsWriting);
        var first = await host.Get<IRecordQueryService>().GetAsync(records.Items[0].Id);
        Assert.Equal(("Bir ", "qwen2.5:7b"), (((InstructionPayload)first!.Payload).Output, first.Lineage.GeneratedByModel));
        Assert.Equal(string.Empty, details.Fields[3].Text);
    });

    [Fact]
    public Task Discarding_forgets_the_model() => UiTest.RunAsync(async () =>
    {
        await using var host = new DesktopTestHost();
        await host.CreateDatasetAsync(DatasetType.Instruction, [new InstructionPayload("Soru?", "", "")]);
        host.AddAIConnection();
        var details = host.Main.Details;
        var row = host.Main.Records.Items[0];
        host.Main.Records.SelectedItem = row;
        await host.WaitForDetailsAsync(row.Id);
        await details.WriteCommand.ExecuteAsync(AIWriteTarget.Answer);

        details.DiscardCommand.Execute(null);
        details.Fields[3].Text = "Elle yazılmış yanıt.";

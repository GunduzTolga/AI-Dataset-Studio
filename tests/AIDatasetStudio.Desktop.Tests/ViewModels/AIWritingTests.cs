        await host.WaitForDetailsAsync(row.Id);

        await details.WriteCommand.ExecuteAsync(AIWriteTarget.Answer);
        Assert.Equal("Set up an AI connection to write with a model: Ollama or LM Studio on this computer is enough.", details.AIError);
        details.OpenAIConnectionsCommand.Execute(null);

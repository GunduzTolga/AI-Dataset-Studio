    [Fact]
    public async Task A_notion_export_is_read_page_by_page_parents_first()
    {
        const string id1 = "0123456789abcdef0123456789abcdef";
        const string id2 = "fedcba9876543210fedcba9876543210";
        var part = Zip(new Dictionary<string, string>
        {
            [$"Destek SSS {id1}/Kargo {id2}.md"] = "# Kargo\n\nKargo ücreti 49,90 TL.\n\n## Süre\n\nİki iş günü.",
            [$"Destek SSS {id1}/İade 11111111111111111111111111111111.md"] = "Ürünler 14 gün içinde iade edilir.",
            [$"Destek SSS {id1}/Ürünler {id2}.csv"] = "Ad,Fiyat\nKalem,10",
            [$"Destek SSS {id1}/Boş 22222222222222222222222222222222.md"] = "# Boş",
            [$"Destek SSS {id1}.md"] = "# Destek SSS\n\nMüşteri sorularının yanıtları.",
        });
        var path = Path.Combine(_directory.FullName, "Export-1234.zip");
        await File.WriteAllBytesAsync(path, Zip(new Dictionary<string, byte[]>
        {
            ["Export-1234-Part-1.zip"] = part,
            ["__MACOSX/._Export-1234-Part-1.zip"] = [1, 2, 3],
        }), Ct);

        var document = await _reader.ReadAsync(path, Ct);

        Assert.Equal((DocumentFormat.Archive, 3, "page"), (document.Format, document.PageCount, document.PositionUnit));
        Assert.Equal(
        [
            (DocumentBlockKind.Heading, 0, "Destek SSS", 1),
            (DocumentBlockKind.Paragraph, 0, "Müşteri sorularının yanıtları.", 1),
            (DocumentBlockKind.Heading, 0, "İade", 2),
            (DocumentBlockKind.Paragraph, 0, "Ürünler 14 gün içinde iade edilir.", 2),
            (DocumentBlockKind.Heading, 0, "Kargo", 3),
            (DocumentBlockKind.Paragraph, 0, "Kargo ücreti 49,90 TL.", 3),
            (DocumentBlockKind.Heading, 2, "Süre", 3),
            (DocumentBlockKind.Paragraph, 0, "İki iş günü.", 3),
        ],
            document.Blocks.Select(b => (b.Kind, b.Level, b.Text, b.Position)));
        Assert.Equal("Export-1234.zip#page=3", document.Reference(3));

        // Passages carry their page as the top of their section.
        var chunks = DocumentChunker.Split(document.Blocks, DocumentChunker.MinTokens, _ => 100);
        Assert.Contains(chunks, c => c.Section.StartsWith("Kargo", StringComparison.Ordinal) && c.First == 3 && c.Text.Contains("49,90", StringComparison.Ordinal));
    }

    [Fact]
    public async Task A_confluence_space_export_leaves_out_its_index_and_files()
    {
        var path = Path.Combine(_directory.FullName, "DESTEK.zip");
        await File.WriteAllBytesAsync(path, Zip(new Dictionary<string, string>
        {
            ["DESTEK/index.html"] = "<html><body><h1>Destek</h1><ul><li><a href=\"Kargo_1001.html\">Kargo</a></li></ul></body></html>",
            ["DESTEK/Kargo_1001.html"] = "<html><body><h1 id=\"title-heading\"><span>Destek : Kargo</span></h1><div id=\"main-content\"><p>Kargo bilgisi.</p></div></body></html>",
            ["DESTEK/Iade-Kosullari_1002.html"] = "<html><head><title>Destek : İade Koşulları</title></head><body><p>İade bilgisi.</p></body></html>",
            ["DESTEK/styles/site.css"] = "body { }",
        }), Ct);

        var document = await _reader.ReadAsync(path, Ct);

        Assert.Equal(
        [
            (DocumentBlockKind.Heading, "İade Koşulları", 1),
            (DocumentBlockKind.Paragraph, "İade bilgisi.", 1),
            (DocumentBlockKind.Heading, "Kargo", 2),
            (DocumentBlockKind.Paragraph, "Kargo bilgisi.", 2),
        ],
            document.Blocks.Select(b => (b.Kind, b.Text, b.Position)));
        Assert.Equal("Iade Kosullari", ArchiveDocument.TitleFromName("DESTEK/Iade-Kosullari_1002.html"));
        Assert.Equal("Kargo", ArchiveDocument.TitleFromName($"Kargo 0123456789abcdef0123456789abcdef.md"));
    }

    [Fact]
    public async Task Archives_without_pages_or_damaged_are_explained()
    {
        var empty = Path.Combine(_directory.FullName, "resimler.zip");
        await File.WriteAllBytesAsync(empty, Zip(new Dictionary<string, byte[]> { ["a.png"] = [1, 2, 3] }), Ct);
        var damaged = Path.Combine(_directory.FullName, "bozuk.zip");
        var bytes = Zip(new Dictionary<string, string> { ["a.md"] = new string('x', 1000) });
        bytes.AsSpan(40, 40).Fill(0xFF);
        await File.WriteAllBytesAsync(damaged, bytes, Ct);

        Assert.Equal(ImportFileError.EmptyArchive, (await Assert.ThrowsAsync<ImportFileException>(() => _reader.ReadAsync(empty, Ct))).Error);
        Assert.Equal(ImportFileError.InvalidDocument, (await Assert.ThrowsAsync<ImportFileException>(() => _reader.ReadAsync(damaged, Ct))).Error);
        Assert.Contains(".zip", _reader.SupportedExtensions);
        Assert.Contains(".html", _reader.SupportedExtensions);
    }

    [Fact]
    public void Broken_markup_still_gives_its_text()
    {
        var (blocks, title) = HtmlDocument.Read(
            "<p>a < b ve <i>c</p></i> <div><p>Açık kalan <b>kalın <li>madde</div><table><tr><td><p>Tek hücrede düzen</table><table><tr><td>hücre<td>ikinci",
